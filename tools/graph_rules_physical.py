# The raw name "density" means a gas density in Gaseous State and a crystal density in
# Solid State, so it is resolved by the TX's chapter.
_DENSITY_BY_CHAPTER = {"Gaseous State": "gas_density", "Solid State": "crystal_density"}
NODE_NAMES.setdefault("crystal_density", "crystal density")


def normalize_node(raw, tx=None):
    """Map a raw from/to string to a canonical node id, or None if it is not a quantity."""
    raw = (raw or "").strip()
    if raw == "density" and tx is not None:
        return _DENSITY_BY_CHAPTER.get(tx.get(CHAPTER_KEY))
    return RAW_TO_NODE.get(raw)
