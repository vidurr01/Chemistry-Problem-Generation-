def _nernst(v, invert=False):
    q = v["molarity"] / v["cathode_ion_concentration"]
    if invert:
        q = 1 / q
    return v["standard_emf"] - C.NERNST_25 / v["electrons"] * log10(q)


def _conc_cell(v, invert=False):
    c1, c2 = v["molarity"], v["concentration_2"]
    return C.NERNST_25 / v["electrons"] * log10((c1 / c2) if invert else (c2 / c1))


_LATTICE = {"simple cubic": (1, lambda r: 2 * r, 6), "body-centred cubic": (2, lambda r: 4 * r / math.sqrt(3), 8),
            "face-centred cubic": (4, lambda r: 2 * math.sqrt(2) * r, 12)}


def _packing(lattice, z=None):
    z0, edge, _ = _LATTICE[lattice]
    z = z or z0
    a = edge(1.0)
    return z * 4 / 3 * math.pi / a ** 3


_VOID_LIMITS = (("linear", 0.0, 2), ("triangular", 0.155, 3), ("tetrahedral", 0.225, 4),
                ("octahedral", 0.414, 6), ("cubic", 0.732, 8))


def _cn(ratio):
    if not 0 < ratio <= 1:
        raise EngineError("radius ratio must be between 0 and 1")
    cn = 2
    for _, lim, c in _VOID_LIMITS:
        if ratio >= lim:
            cn = c
    return cn


_FRACTIONS = {"1/3": 1 / 3, "1/2": 1 / 2, "2/3": 2 / 3, "all": 1.0}


def _formula_from_voids(v, wrong=False):
    """Anions form ccp (4 per cell); cations fill a fraction of the voids."""
    voids = {"tetrahedral": 8, "octahedral": 4}[v["void_type"]]
    if wrong:
        voids = 12 - voids          # swaps tetrahedral/octahedral counts
    cations = voids * _FRACTIONS[v["fraction_occupied"]]
    anions = 4
    g = math.gcd(int(round(cations * 6)), anions * 6)
    a, b = int(round(cations * 6)) // g, anions * 6 // g
    if abs(cations * 6 - round(cations * 6)) > 1e-6:
        raise EngineError("fraction gives no whole-number formula")
    return f"A{'' if a == 1 else a}B{'' if b == 1 else b}"


